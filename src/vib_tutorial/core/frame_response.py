"""The Frame builder's forced response, worked two ways: the conventional real-mode model and the state space.

Conventional
------------
The undamped modes (K φ = ω² M φ, `frame.modes`, mass-normalized) uncouple M and K. The usual model keeps them for
the damping too: each mode a single oscillator, η̈_r + c_r η̇_r + ω_r² η_r = φ_rᵀ f, with c_r = φ_rᵀ C φ_r (so
ζ_r = c_r / 2ω_r) and the off-diagonal φ_rᵀ C φ_s dropped, and q = Σ φ_r η_r. That is exact when the damping is
proportional (ΦᵀCΦ diagonal): Rayleigh's C = αM + βK, say, which gives ζ_r = (α/ω_r + βω_r)/2, chosen here to
be the frame's ζ at its first two modes (`rayleigh`). A damper somewhere (between two nodes, or to the ground)
is not proportional: its share of ΦᵀCΦ couples the modes, and the conventional model ignores that.

State space
-----------
The whole M q̈ + C q̇ + K q = f, written first order, x' = A x + B f with x = (q, q̇) and
A = [0 I; −M⁻¹K −M⁻¹C]: nothing dropped. Its eigenvalues are the damped poles, λ = −ζω ± iω√(1 − ζ²) for a mode
under light damping, and its eigenvectors the complex modes ψ, each node with its own phase: with a damper the
nodes no longer pass through zero together (MPC < 1, `complex_modes.complexity`). A DOF with no mass but a
damper on it (a lumped beam's turn with a torsion damper) has no q̈: its row is first order, C q̇ + K q = f,
and it adds one real root, a relaxation, not a mode. DOFs with neither mass nor damping are condensed out
exactly, statically, as for the modes.

Responses
---------
`frf` is the receptance from one DOF's force to another DOF's displacement, by A's eigenvectors. `response` steps
a `Load` from rest exactly: the load is generated by states of its own (a constant for a step, a sine and a
cosine turning at Ω for a harmonic force), stacked under A, so one matrix exponential e^{A h} carries the
structure and its load over each step without approximating either; an impulse is the state it leaves,
x(0⁺) = B J. With proportional damping the two models agree to round-off (a test checks); with a damper they part
by as much as the dropped coupling matters.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

import numpy as np
import scipy.linalg
import scipy.optimize

from .complex_modes import Complexity, complexity
from .frame import TWO_PI, Assembly, Frame, FrameError, Modes, assemble, condense, modes

SAMPLES = 2400  # in a time response
RECORD_PERIODS = 12  # of the first mode, in a response's record
DRIVE_PERIODS = 20  # of a harmonic load's
FRF_MODES = 8  # the FRF's band reaches past this many modes
FRF_POINTS = 600
OSCILLATES = 1e-6  # |Im λ| above this × |λ|: a mode, not a real root
STILL = 1e-9  # |λ| below this × the largest: a rigid (mechanism) root
WELL_POSED = 1e10  # cond of A's eigenvectors above this: work the FRF by solving instead


class LoadKind(Enum):
    HARMONIC = "Harmonic"
    IMPULSE = "Impulse"
    STEP = "Step"


LOAD_KINDS = tuple(LoadKind)


@dataclass(frozen=True)
class Load:
    """A force on one DOF (N; a moment on a turn, N·m), from rest at t = 0: F sin Ωt, an impulse of F·1 s
    (N·s), or a step of F."""

    node: int = 0
    dof: int = 1  # 0 u, 1 v, 2 θ
    kind: LoadKind = LoadKind.IMPULSE
    size: float = 100.0
    hz: float = 10.0

    @property
    def index(self) -> int:
        return 3 * self.node + self.dof


def rayleigh(zeta: float, hz: np.ndarray) -> tuple[float, float]:
    """(α, β) of C = αM + βK with ζ at the first two modes of hz (only β, ζ at mode 1, if there is one)."""
    w = TWO_PI * hz[hz > 0]
    if zeta <= 0 or w.size == 0:
        return 0.0, 0.0
    if w.size == 1:
        return 0.0, 2 * zeta / w[0]
    w1, w2 = w[0], w[1]
    return 2 * zeta * w1 * w2 / (w1 + w2), 2 * zeta / (w1 + w2)


@dataclass(frozen=True)
class StateModel:
    """x' = A x + B f, f the force on every DOF; every DOF's displacement is `out` x."""

    A: np.ndarray
    B: np.ndarray  # (states, n_dof)
    out: np.ndarray  # (n_dof, states)

    @property
    def size(self) -> int:
        return self.A.shape[0]


def exact_model(frame: Frame, a: Assembly, result: Modes) -> StateModel:
    """The state space of the whole M, C, K (the dampers and the Rayleigh damping), massless undamped DOFs
    condensed out; a massless DOF with a damper keeps a first-order state."""
    free = a.free_dofs
    M, C, K = a.M[np.ix_(free, free)], a.C[np.ix_(free, free)], a.K[np.ix_(free, free)]
    mass = np.any(M != 0, axis=1)
    damped = ~mass & np.any(C != 0, axis=1)
    keep = mass | damped
    if keep.all():
        R = np.eye(free.size)
    else:
        K, M, R = condense(K, M, keep)
        C = C[np.ix_(keep, keep)]  # the dropped DOFs have no damping: R's static part adds none
    alpha, beta = rayleigh(frame.zeta, result.hz)
    C = C + alpha * M + beta * K
    M, C, K = (0.5 * (X + X.T) for X in (M, C, K))
    m, d = mass[keep], damped[keep]
    qm, qd = np.flatnonzero(m), np.flatnonzero(d)
    nk, nm = int(keep.sum()), qm.size
    A = np.zeros((nk + nm, nk + nm))
    Bk = np.zeros((nk + nm, nk))
    Minv = np.linalg.inv(M[np.ix_(qm, qm)])
    Cv, Kq = C[np.ix_(qm, qm)], K[qm]
    A[qm, nk + np.arange(nm)] = 1.0
    Bk[nk:, qm] = Minv
    if qd.size:  # C_dd q̇_d = f_d − C_dm v − K_d q
        Cdd = C[np.ix_(qd, qd)]
        if np.linalg.cond(Cdd) > 1e12:
            raise FrameError("A damper's massless end can move with nothing to resist it: add a mass or a spring.")
        D = np.linalg.inv(Cdd)
        Cmd, Cdm = C[np.ix_(qm, qd)], C[np.ix_(qd, qm)]
        A[np.ix_(qd, nk + np.arange(nm))] = -D @ Cdm
        A[qd, :nk] = -D @ K[qd]
        Bk[np.ix_(qd, qd)] = D
        Cv = Cv - Cmd @ D @ Cdm
        Kq = Kq - Cmd @ D @ K[qd]
        Bk[nk:, qd] = -Minv @ Cmd @ D
    A[nk:, :nk] = -Minv @ Kq
    A[nk:, nk:] = -Minv @ Cv
    B = np.zeros((nk + nm, frame.n_dof))
    B[:, free] = Bk @ R.T
    out = np.zeros((frame.n_dof, nk + nm))
    out[free, :nk] = R
    return StateModel(A, B, out)


def modal_damping(frame: Frame, a: Assembly, result: Modes) -> np.ndarray:
    """c_r = φ_rᵀ C φ_r for each mode, with the Rayleigh part α + βω_r² (ζ_r = c_r / 2ω_r)."""
    phi = result.shapes
    alpha, beta = rayleigh(frame.zeta, result.hz)
    w = TWO_PI * result.hz
    return np.einsum("ir,ij,jr->r", phi, a.C, phi) + alpha + beta * w**2


def conventional_model(frame: Frame, a: Assembly, result: Modes) -> StateModel:
    """One oscillator per undamped mode, ΦᵀCΦ's diagonal kept: η'' + c_r η' + ω_r² η = φ_rᵀ f, q = Φ η."""
    phi = result.shapes
    n = phi.shape[1]
    w = TWO_PI * result.hz
    A = np.zeros((2 * n, 2 * n))
    A[:n, n:] = np.eye(n)
    A[n:, :n] = -np.diag(w**2)
    A[n:, n:] = -np.diag(modal_damping(frame, a, result))
    B = np.zeros((2 * n, frame.n_dof))
    B[n:] = phi.T
    out = np.zeros((frame.n_dof, 2 * n))
    out[:, :n] = phi
    return StateModel(A, B, out)


# -------------------------------------------------------------------- the two side by side
@dataclass(frozen=True)
class DampedMode:
    """An undamped mode beside the state space's mode that pairs with it."""

    index: int  # the undamped mode's, from 0
    hz: float  # undamped
    zeta_conventional: float  # c_r / 2ω_r
    pole: complex | None  # the exact pole (Im > 0); None if the mode is overdamped (or a mechanism)
    shape: np.ndarray | None  # its ψ over every DOF, largest entry 1
    measures: Complexity | None

    @property
    def hz_exact(self) -> float:
        return abs(self.pole) / TWO_PI if self.pole is not None else float("nan")

    @property
    def zeta_exact(self) -> float:
        return -self.pole.real / abs(self.pole) if self.pole is not None else float("nan")


@dataclass(frozen=True)
class Formulations:
    result: Modes
    exact: StateModel
    conventional: StateModel
    modes: tuple[DampedMode, ...]
    roots: np.ndarray  # the state space's real roots that aren't rigid: relaxations, overdamped modes (1/s, < 0)
    proportional: bool  # ΦᵀCΦ diagonal (to round-off)


def _mac(phi: np.ndarray, psi: np.ndarray) -> float:
    den = float(phi @ phi) * float(np.vdot(psi, psi).real)
    return float(abs(np.vdot(phi, psi)) ** 2 / den) if den > 0 else 0.0


def formulations(frame: Frame, assembly: Assembly | None = None, result: Modes | None = None) -> Formulations:
    a = assembly if assembly is not None else assemble(frame)
    result = result if result is not None else modes(frame, a)
    exact = exact_model(frame, a, result)
    conventional = conventional_model(frame, a, result)
    lam, V = np.linalg.eig(exact.A)
    top = float(np.abs(lam).max()) if lam.size else 0.0
    upper = np.flatnonzero(lam.imag > OSCILLATES * np.abs(lam))
    psi = exact.out @ V[:, upper]
    elastic = np.flatnonzero(result.hz > 0)
    pole: dict[int, int] = {}
    if upper.size and elastic.size:
        cost = np.array(
            [
                [
                    1.0
                    - _mac(result.shapes[:, r], psi[:, k])
                    + abs(np.log(abs(lam[upper[k]]) / (TWO_PI * result.hz[r])))
                    for k in range(upper.size)
                ]
                for r in elastic
            ]
        )
        rows, cols = scipy.optimize.linear_sum_assignment(cost)
        pole = {int(elastic[r]): int(c) for r, c in zip(rows, cols, strict=True)}
    c = modal_damping(frame, a, result)
    w = TWO_PI * result.hz
    out = []
    for r in range(result.hz.size):
        zeta = c[r] / (2 * w[r]) if w[r] > 0 else float("nan")
        if r in pole:
            k = pole[r]
            shape = psi[:, k] / psi[np.argmax(np.abs(psi[:, k])), k]
            out.append(
                DampedMode(r, float(result.hz[r]), float(zeta), complex(lam[upper[k]]), shape, complexity(shape))
            )
        else:
            out.append(DampedMode(r, float(result.hz[r]), float(zeta), None, None, None))
    real = lam[np.abs(lam.imag) <= OSCILLATES * np.abs(lam)].real
    roots = np.sort(real[real < -STILL * top])[::-1]
    coupling = result.shapes.T @ a.C @ result.shapes
    off = coupling - np.diag(np.diag(coupling))
    proportional = bool(np.abs(off).max(initial=0.0) <= 1e-9 * max(np.abs(coupling).max(initial=0.0), 1e-300))
    return Formulations(result, exact, conventional, tuple(out), roots, proportional)


# -------------------------------------------------------------------- frequency response
def frf_grid(hz: np.ndarray, points: int = FRF_POINTS) -> np.ndarray:
    """Hz: log-spaced over the first FRF_MODES modes, denser over each; none falls on a natural frequency."""
    fn = hz[hz > 0][:FRF_MODES]
    if fn.size == 0:
        return np.geomspace(0.1, 100.0, points)
    base = np.geomspace(0.3 * fn.min(), 1.3 * fn.max(), points)
    peaks = [f * (1 + np.linspace(-0.08, 0.08, 80)) for f in fn]  # an even count: f itself left out
    return np.unique(np.concatenate([base, *peaks]))


def frf(model: StateModel, freqs_hz: np.ndarray, inp: int, out: int) -> np.ndarray:
    """The receptance from a force on DOF `inp` to DOF `out`'s displacement (m/N), at each frequency."""
    s = 1j * TWO_PI * np.asarray(freqs_hz, dtype=float)
    b, c = model.B[:, inp], model.out[out]
    lam, V = np.linalg.eig(model.A)
    if np.linalg.cond(V) < WELL_POSED:
        weight = (c @ V) * np.linalg.solve(V, b)
        return np.sum(weight / (s[:, None] - lam), axis=1)
    eye = np.eye(model.size)
    return np.array([c @ np.linalg.solve(si * eye - model.A, b) for si in s])


# -------------------------------------------------------------------- time response
def record(hz: np.ndarray, load: Load) -> np.ndarray:
    """The times (s) a response is worked out at: RECORD_PERIODS of the first mode, or DRIVE_PERIODS of a
    harmonic load if that's longer."""
    fn = hz[hz > 0]
    span = RECORD_PERIODS / fn[0] if fn.size else 1.0
    if load.kind is LoadKind.HARMONIC and load.hz > 0:
        span = max(span, DRIVE_PERIODS / load.hz)
    return np.linspace(0.0, span, SAMPLES)


def response(model: StateModel, load: Load, t: np.ndarray) -> np.ndarray:
    """Every DOF's displacement (len(t), n_dof) under the load, from rest, exactly at each time (t evenly
    spaced from 0): the load's own states stacked under A, one exponential a step."""
    n = model.size
    b = model.B[:, load.index] * load.size
    if load.kind is LoadKind.IMPULSE:
        A, z0 = model.A, b.copy()
    elif load.kind is LoadKind.STEP:
        A = np.zeros((n + 1, n + 1))
        A[:n, :n], A[:n, n] = model.A, b
        z0 = np.zeros(n + 1)
        z0[n] = 1.0
    else:  # (s, c)' = Ω (c, −s) from (0, 1): s = sin Ωt
        omega = TWO_PI * load.hz
        A = np.zeros((n + 2, n + 2))
        A[:n, :n], A[:n, n] = model.A, b
        A[n, n + 1], A[n + 1, n] = omega, -omega
        z0 = np.zeros(n + 2)
        z0[n + 1] = 1.0
    h = float(t[1] - t[0]) if t.size > 1 else 0.0
    E = scipy.linalg.expm(A * h)
    z = np.empty((t.size, z0.size))
    z[0] = z0
    for k in range(1, t.size):
        z[k] = E @ z[k - 1]
    return z[:, :n] @ model.out.T


@dataclass(frozen=True)
class Responses:
    freqs: np.ndarray  # Hz
    frf_exact: np.ndarray
    frf_conventional: np.ndarray
    t: np.ndarray
    exact: np.ndarray  # (samples, n_dof)
    conventional: np.ndarray


def responses(f: Formulations, load: Load, out: int) -> Responses:
    """Both models' FRF (load's DOF to `out`) and time response to the load."""
    freqs = frf_grid(f.result.hz)
    t = record(f.result.hz, load)
    return Responses(
        freqs,
        frf(f.exact, freqs, load.index, out),
        frf(f.conventional, freqs, load.index, out),
        t,
        response(f.exact, load, t),
        response(f.conventional, load, t),
    )
