"""Write `src/vib_tutorial/gui/font_metrics.py`: how wide each character sets in the figures' two fonts, so a
figure's labels can be placed without Qt (#316 D7).

    uv run python scripts/font_metrics.py

It measures with Qt, offscreen, at 1000 px: the UI's sans-serif (Qt's default font here) and the notes' math font
(STIX Two Text, bundled) in italic, over printable ASCII, Greek and every character a figure's labels use. Rerun it
when a figure brings in a new character (`tests/test_figures.py` checks the tables cover them) or the UI font
changes (#316 D10).
"""

from __future__ import annotations

import os
import re
import string
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6 import QtGui, QtWidgets

from vib_tutorial.gui import figures, maths, notes_render

OUT = Path(__file__).resolve().parents[1] / "src" / "vib_tutorial" / "gui" / "font_metrics.py"
SIZE = 1000


def label_chars() -> set[str]:
    """Every character in the figures' texts."""
    found: set[str] = set()
    for draw in figures.all_figures().values():
        for text in re.findall(r"<text[^>]*>(.*?)</text>", draw(), re.S):
            found |= set(re.sub(r"<[^>]+>", "", text))
    return found


def main() -> None:
    QtWidgets.QApplication.instance() or QtWidgets.QApplication([])
    notes_render.install()
    greek = {chr(c) for c in range(0x391, 0x3CA) if chr(c).isalpha()}
    chars = sorted(set(string.printable[:95]) | greek | label_chars())
    tables = {}
    for name, italic in (("SANS", False), ("MATH_ITALIC", True)):
        font = QtGui.QFont(maths.FONT) if italic else QtGui.QFont()
        font.setItalic(italic)
        font.setPixelSize(SIZE)
        metrics = QtGui.QFontMetricsF(font)
        tables[name] = (
            QtGui.QFontInfo(font).family(),
            {c: round(metrics.horizontalAdvance(c) / SIZE, 4) for c in chars},
        )
    lines = [
        '"""How wide each character sets in the figures\' fonts, in ems: generated by `scripts/font_metrics.py` (rerun',
        "it when a figure brings in a new character or the UI font changes). `width` measures a label with them, which",
        "places a figure's sub- and superscripts without Qt (#316 D7); in the app Qt measures (`notes_render.install`).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import re",
        "",
    ]
    lines.append(f"SANS_FAMILY = {tables['SANS'][0]!r}  # the UI font the SANS table was measured in")
    lines.append("")
    for name, (family, table) in tables.items():
        lines.append(f"# {family}")
        lines.append(f"{name} = {{")
        lines += [f"    {c!r}: {w}," for c, w in table.items()]
        lines.append("}")
        lines.append("")
    lines += [
        "",
        "def width(s: str, italic: bool, size: float) -> float:",
        '    """How wide `s` (its markup dropped) sets at `size` px; a character not in the table counts as an \'n\'."""',
        "    table = MATH_ITALIC if italic else SANS",
        '    return size * sum(table.get(c, table["n"]) for c in re.sub(r"<[^>]+>", "", s))',
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(chars)} characters → {OUT}")


if __name__ == "__main__":
    main()
